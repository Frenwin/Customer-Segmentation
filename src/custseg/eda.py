"""Data profiling (raw layer) and exploratory data analysis (warehouse / mart layer).

profile_raw()      -> per-table / per-column profile of the source files  (04_.../reports/data_profiling_report.md)
univariate()       -> distributions of the customer-level variables
bivariate()        -> relationships between pairs (value vs satisfaction, delivery vs review, ...)
multivariate()     -> correlation structure + PCA of the screened features
"""
from __future__ import annotations

import json

import numpy as np
import pandas as pd
from scipy import stats

from custseg import config, db, viz
from custseg.features import ALL_CANDIDATES, customer_mart, revenue_orders

FIG = config.EDA_FIG


def profile_raw() -> pd.DataFrame:
    rows = []
    for table in config.RAW_FILES:
        df = db.query(f"SELECT * FROM raw.{table}")
        n = len(df)
        for c in df.columns:
            s = df[c]
            num = pd.to_numeric(s, errors="coerce")
            is_num = num.notna().sum() >= 0.95 * s.notna().sum() and s.notna().sum() > 0
            dt = pd.to_datetime(s, errors="coerce", format="%Y-%m-%d %H:%M:%S") if not is_num else None
            is_dt = dt is not None and dt.notna().sum() >= 0.95 * s.notna().sum() and s.notna().sum() > 0
            kind = "numeric" if is_num else ("datetime" if is_dt else "text")
            r = {"table": table, "column": c, "rows": n, "inferred_type": kind,
                 "null_count": int(s.isna().sum()), "null_pct": float(s.isna().mean()),
                 "distinct": int(s.nunique()), "distinct_pct": float(s.nunique() / n),
                 "example": str(s.dropna().iloc[0])[:40] if s.notna().any() else ""}
            if is_num:
                r.update({"min": float(num.min()), "p50": float(num.median()), "max": float(num.max()),
                          "mean": float(num.mean())})
            elif is_dt:
                r.update({"min": str(dt.min()), "max": str(dt.max())})
            rows.append(r)
    prof = pd.DataFrame(rows)
    out = config.EDA_REPORTS
    prof.to_csv(out / "data_profiling.csv", index=False)
    man = json.loads((config.ROOT / "02_data" / "dataset_manifest.json").read_text())
    lines = ["# Data Profiling Report - Raw Layer", "",
             f"Dataset: {config.DATASET_NAME} · version `{man['dataset_version']}` · license {config.DATASET_LICENSE}", "",
             "Profile of the source files exactly as loaded into schema `raw` (all columns TEXT; types below are "
             "inferred). Generated by `custseg.eda.profile_raw()`.", "", "## Tables", "",
             "| Table | Rows | Columns | File size |", "|---|---:|---:|---:|"]
    for t, f in man["files"].items():
        lines.append(f"| {t} | {f['rows']:,} | {len(f['columns'])} | {f['bytes'] / 1e6:.1f} MB |")
    lines += ["", "## Columns", "", "| Table | Column | Type | Null % | Distinct | Min | Median | Max | Example |",
              "|---|---|---|---:|---:|---|---|---|---|"]
    for r in prof.itertuples():
        mn = "" if pd.isna(getattr(r, "min", np.nan)) else (f"{r.min:,.2f}" if isinstance(r.min, float) else r.min)
        md = "" if pd.isna(getattr(r, "p50", np.nan)) else f"{r.p50:,.2f}"
        mx = "" if pd.isna(getattr(r, "max", np.nan)) else (f"{r.max:,.2f}" if isinstance(r.max, float) else r.max)
        lines.append(f"| {r.table} | {r.column} | {r.inferred_type} | {r.null_pct:.2%} | {r.distinct:,} | {mn} | {md} | "
                     f"{mx} | `{r.example}` |")
    lines += ["", "## Key observations", "",
              "- `customer_id` is unique per **order** (99,441 = number of orders); the person is `customer_unique_id` "
              f"({prof[(prof.table == 'customers') & (prof.column == 'customer_unique_id')].distinct.iloc[0]:,} distinct).",
              "- Orders span 2016-09 to 2018-10, but 2016 has only 329 orders with a collection gap and Sep/Oct 2018 only "
              "20 orders: the analysis window is restricted to 2017-01-01 .. 2018-08-31 (20 complete months).",
              "- 1,000,163 geolocation rows for ~19k zip prefixes (heavy duplication) -> aggregated to one median point "
              "per prefix.",
              "- No customer demographics (gender / age), no registration date, no product cost, no discounts and no "
              "marketing data exist in the source. Consequences: acquisition date = first purchase, revenue "
              "(not profit) contribution only, KPIs of PRD 8.4 (engagement) are out of scope.",
              "- Reviews: 814 duplicated review_id and 551 orders with >1 review -> latest answer kept.",
              "- 610 products without category -> `uncategorized`.", ""]
    (out / "data_profiling_report.md").write_text("\n".join(lines), encoding="utf-8")
    return prof


def univariate() -> dict:
    import matplotlib.pyplot as plt
    cm = customer_mart()
    cols = ["recency_days", "frequency", "monetary", "avg_items_per_order", "avg_installments", "avg_review_score",
            "avg_delivery_days", "freight_ratio", "late_delivery_share"]
    desc = cm[cols].describe(percentiles=[.25, .5, .75, .9, .99]).T
    desc["skew"] = cm[cols].skew()
    desc.to_csv(config.EDA_REPORTS / "univariate_summary.csv")
    fig, axes = plt.subplots(3, 3, figsize=(12, 8.4))
    for ax, c in zip(axes.flat, cols):
        v = cm[c].dropna()
        if c in ("frequency",):
            vc = v.value_counts().sort_index()
            ax.bar(vc.index.astype(str), vc.values, color=viz.BLUE)
            ax.set_yscale("log")
            ax.set_title(f"{c} (log count)")
        elif c in ("avg_review_score",):
            vc = v.round().value_counts().sort_index()
            ax.bar(vc.index.astype(int).astype(str), vc.values, color=viz.BLUE)
            ax.set_title(c)
        else:
            ax.hist(v.clip(upper=v.quantile(0.99)), bins=50, color=viz.BLUE, edgecolor=viz.SURFACE, linewidth=0.4)
            ax.set_title(f"{c} (clipped p99) · skew {v.skew():.1f}")
    fig.tight_layout()
    viz.save(fig, FIG / "univariate_distributions.png")
    o = revenue_orders()
    status = db.query("SELECT order_status, count(*) n FROM dw.fact_orders WHERE is_in_window GROUP BY 1 ORDER BY 2 DESC")
    pay = o.payment_type.value_counts(normalize=True)
    return {"summary": desc, "status": status, "payment_share": pay,
            "one_time_share": float((cm.frequency == 1).mean())}


def bivariate() -> dict:
    import matplotlib.pyplot as plt
    o = revenue_orders()
    res = {}
    fig, axes = plt.subplots(1, 3, figsize=(13, 3.6))
    # delivery days vs review
    d = o.dropna(subset=["delivery_days", "review_score"])
    band = pd.cut(d.delivery_days, [0, 7, 14, 21, 30, 60, 300], labels=["<=7", "8-14", "15-21", "22-30", "31-60", ">60"])
    t = d.groupby(band, observed=True).review_score.mean()
    axes[0].bar(t.index.astype(str), t.values, color=viz.BLUE, width=0.65)
    axes[0].set_ylim(1, 5)
    axes[0].set_title("Avg review score by delivery time (days)")
    for i, v in enumerate(t.values):
        axes[0].text(i, v + 0.05, f"{v:.2f}", ha="center", fontsize=7, color=viz.INK2)
    rho = stats.spearmanr(d.delivery_days, d.review_score)
    res["delivery_vs_review_spearman"] = float(rho.statistic)
    late = o.dropna(subset=["is_late", "review_score"]).groupby("is_late").review_score.mean()
    res["review_on_time"], res["review_late"] = float(late[False]), float(late[True])
    # order value vs installments
    ib = pd.cut(o.installments.fillna(1), [-1, 1, 3, 6, 10, 30], labels=["1x", "2-3x", "4-6x", "7-10x", ">10x"])
    t2 = o.groupby(ib, observed=True).order_value.median()
    axes[1].bar(t2.index.astype(str), t2.values, color=viz.BLUE, width=0.65)
    axes[1].set_title("Median order value (R$) by installments")
    for i, v in enumerate(t2.values):
        axes[1].text(i, v, f"{v:,.0f}", ha="center", va="bottom", fontsize=7, color=viz.INK2)
    res["installments_vs_value_spearman"] = float(stats.spearmanr(o.installments.fillna(1), o.order_value).statistic)
    # freight ratio vs value
    fr = o.freight_value / o.order_value
    vb = pd.qcut(o.order_value, 5, labels=["Q1", "Q2", "Q3", "Q4", "Q5"])
    t3 = fr.groupby(vb, observed=True).median() * 100
    axes[2].bar(t3.index.astype(str), t3.values, color=viz.BLUE, width=0.65)
    axes[2].set_title("Median freight share of order value (%) by value quintile")
    for i, v in enumerate(t3.values):
        axes[2].text(i, v, f"{v:.0f}%", ha="center", va="bottom", fontsize=7, color=viz.INK2)
    fig.tight_layout()
    viz.save(fig, FIG / "bivariate_relationships.png")
    # monetary by repeat status (Mann-Whitney)
    cm = customer_mart()
    a, b = cm[cm.is_repeat_customer].monetary, cm[~cm.is_repeat_customer].monetary
    mw = stats.mannwhitneyu(a, b)
    res.update({"median_monetary_repeat": float(a.median()), "median_monetary_one_time": float(b.median()),
                "repeat_vs_one_time_p": float(mw.pvalue),
                "aov_repeat": float(cm[cm.is_repeat_customer].avg_order_value.median()),
                "aov_one_time": float(cm[~cm.is_repeat_customer].avg_order_value.median())})
    return res


def multivariate() -> dict:
    import matplotlib.pyplot as plt
    from sklearn.decomposition import PCA
    from sklearn.preprocessing import StandardScaler
    cm = customer_mart()
    cols = [c for c in ALL_CANDIDATES if cm[c].notna().mean() > 0.5]
    rho = cm[cols].astype(float).corr("spearman")
    rho.to_csv(config.EDA_REPORTS / "spearman_correlation.csv")
    fig, ax = plt.subplots(figsize=(9, 7.5))
    cmap = matplotlib_diverging()
    im = ax.imshow(rho.values, cmap=cmap, vmin=-1, vmax=1)
    ax.set_xticks(range(len(cols)), cols, rotation=75, fontsize=7)
    ax.set_yticks(range(len(cols)), cols, fontsize=7)
    for (i, j), v in np.ndenumerate(rho.values):
        if i != j and abs(v) >= 0.5:
            ax.text(j, i, f"{v:.2f}", ha="center", va="center", fontsize=6, color="#ffffff" if abs(v) > 0.8 else viz.INK)
    ax.grid(False)
    ax.set_title("Spearman correlation of candidate features (|rho| >= 0.5 labelled)")
    fig.colorbar(im, ax=ax, shrink=0.7)
    viz.save(fig, FIG / "multivariate_correlation.png")
    feats = ["recency_days", "frequency", "monetary", "avg_items_per_order", "avg_installments", "avg_review_score",
             "late_delivery_share", "freight_ratio"]
    X = cm[feats].astype(float).copy()
    for c in ["frequency", "monetary", "avg_items_per_order"]:
        X[c] = np.log1p(X[c])
    X = StandardScaler().fit_transform(X.fillna(X.median()))
    pca = PCA().fit(X)
    load = pd.DataFrame(pca.components_[:3].T, index=feats, columns=["PC1", "PC2", "PC3"])
    load.to_csv(config.EDA_REPORTS / "pca_loadings.csv")
    pairs = [(a, b, float(rho.loc[a, b])) for i, a in enumerate(cols) for b in cols[i + 1:] if abs(rho.loc[a, b]) > 0.8]
    return {"high_corr_pairs": pairs, "pca_explained": pca.explained_variance_ratio_.tolist(), "pca_loadings": load}


def matplotlib_diverging():
    from matplotlib.colors import LinearSegmentedColormap
    return LinearSegmentedColormap.from_list("div", ["#c2410c", "#eb6834", "#f6c8b2", "#efeeea", "#b7d3f6",
                                                     "#3987e5", "#184f95"])


def run_all() -> dict:
    config.ensure_dirs()
    res = {"profile": profile_raw(), "univariate": univariate(), "bivariate": bivariate(),
           "multivariate": multivariate()}
    summ = {"one_time_share": res["univariate"]["one_time_share"],
            **{k: v for k, v in res["bivariate"].items()},
            "high_corr_pairs": res["multivariate"]["high_corr_pairs"],
            "pca_explained_first3": res["multivariate"]["pca_explained"][:3]}
    (config.EDA_REPORTS / "eda_summary.json").write_text(json.dumps(summ, indent=2, default=float), encoding="utf-8")
    return res
